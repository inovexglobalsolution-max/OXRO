/// Sub-categories for a category label (empty when unknown).
List<String> subcategoriesFor(String label) =>
    foodSubcategories[label] ?? const [];

/// Look up a category by label, or null.
FoodCategory? foodCategoryFor(String label) {
  for (final c in foodCategories) {
    if (c.label == label) return c;
  }
  return null;
}
